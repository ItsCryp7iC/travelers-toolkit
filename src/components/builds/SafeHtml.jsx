import React, { useMemo } from 'react';
import RotationBadge from './RotationBadge';

// Permitted HTML tags for editorial markdown rendering
const ALLOWED_TAGS = new Set([
  'p',
  'strong',
  'b',
  'em',
  'i',
  'span',
  'br',
  'ul',
  'ol',
  'li',
  'code',
  'h1',
  'h2',
  'h3',
  'h4',
  'a',
  'div',
  'blockquote',
]);

/**
 * Validate that an href URL is strictly HTTP or HTTPS
 */
function isSafeUrl(url) {
  if (!url) return false;
  const trimmed = url.trim().toLowerCase();
  return (
    trimmed.startsWith('https://') ||
    trimmed.startsWith('http://') ||
    trimmed.startsWith('#')
  );
}

/**
 * Recursively converts allowed DOM nodes to React elements
 */
function domToReact(node, key) {
  // 1. Text node
  if (node.nodeType === 3 /* Node.TEXT_NODE */) {
    return node.nodeValue;
  }

  // 2. Element node
  if (node.nodeType === 1 /* Node.ELEMENT_NODE */) {
    const tagName = node.tagName.toLowerCase();

    // Check if tag is permitted
    if (!ALLOWED_TAGS.has(tagName)) {
      return null;
    }

    // Convert child nodes
    const children = Array.from(node.childNodes).map((child, index) =>
      domToReact(child, `${key}-${index}`),
    );

    // Special case: Rotation Badge placeholder generated by importer
    if (
      tagName === 'span' &&
      (node.classList?.contains('tt-rotation-badge') ||
        node.hasAttribute('data-rotation'))
    ) {
      const rotation =
        node.getAttribute('data-rotation') || node.textContent || '';
      return <RotationBadge key={key} rotation={rotation} />;
    }

    // Link tag: sanitize href and add external security attributes
    if (tagName === 'a') {
      const rawHref = node.getAttribute('href') || '';
      if (!isSafeUrl(rawHref)) {
        return <span key={key}>{children}</span>;
      }

      return (
        <a
          key={key}
          href={rawHref}
          target="_blank"
          rel="noopener noreferrer"
          className="text-sky-400 hover:text-sky-300 font-medium underline underline-offset-2 transition-colors inline-flex items-center gap-0.5"
        >
          <span>{children}</span>
          <span className="text-[10px] text-sky-400/80" aria-hidden="true">
            ↗
          </span>
        </a>
      );
    }

    // Standard allowed tags with styled Tailwind defaults
    switch (tagName) {
      case 'p':
        return (
          <p
            key={key}
            className="mb-2 last:mb-0 leading-relaxed text-slate-300 text-xs sm:text-sm"
          >
            {children}
          </p>
        );
      case 'strong':
      case 'b':
        return (
          <strong key={key} className="font-semibold text-white">
            {children}
          </strong>
        );
      case 'em':
      case 'i':
        return (
          <em key={key} className="italic text-slate-200">
            {children}
          </em>
        );
      case 'br':
        return <br key={key} />;
      case 'ul':
        return (
          <ul
            key={key}
            className="list-disc list-inside space-y-1 my-2 text-slate-300 text-xs sm:text-sm"
          >
            {children}
          </ul>
        );
      case 'ol':
        return (
          <ol
            key={key}
            className="list-decimal list-inside space-y-1 my-2 text-slate-300 text-xs sm:text-sm"
          >
            {children}
          </ol>
        );
      case 'li':
        return (
          <li key={key} className="leading-relaxed">
            {children}
          </li>
        );
      case 'code':
        return (
          <code
            key={key}
            className="px-1.5 py-0.5 rounded bg-slate-800 text-sky-300 font-mono text-xs"
          >
            {children}
          </code>
        );
      case 'h1':
      case 'h2':
      case 'h3':
      case 'h4':
        return (
          <h4
            key={key}
            className="font-bold text-slate-200 mt-3.5 mb-1.5 text-xs sm:text-sm tracking-wide uppercase"
          >
            {children}
          </h4>
        );
      case 'blockquote':
        return (
          <blockquote
            key={key}
            className="border-l-2 border-sky-500/50 pl-3 my-2 text-slate-400 italic text-xs"
          >
            {children}
          </blockquote>
        );
      case 'span':
      case 'div':
      default:
        return <span key={key}>{children}</span>;
    }
  }

  return null;
}

/**
 * Normalizes Markdown patterns (headings, bullet lists, numbered lists) inside HTML
 * into semantic HTML tags (<h4>, <ul>, <ol>, <li>).
 *
 * Upstream notes frequently contain Markdown headings (e.g. "## Viable Weapons with WIP Calculations:")
 * and bullet items (e.g. "- Nocturne's Curtain Call") that were stored inside <p> blocks separated by <br /> or newlines.
 * Converting these to semantic tags ensures accessible, properly styled headings and lists.
 */
function normalizeMarkdownInHtml(html) {
  if (!html || typeof html !== 'string') return '';

  // If there are no HTML tags at all, wrap in <p> so block parsing applies uniformly
  const source = /<[a-z][\s\S]*>/i.test(html) ? html : `<p>${html}</p>`;

  return source.replace(/<(p|div)>([\s\S]*?)<\/\1>/gi, (match, tag, inner) => {
    // Split on <br /> tags or raw newlines
    const rawLines = inner.split(/<br\s*\/?>|\n/gi);

    const blocks = [];
    let currentList = null; // { type: 'ul' | 'ol', items: [] }
    let currentParaLines = [];

    const flushPara = () => {
      if (currentParaLines.length > 0) {
        const text = currentParaLines.join('<br />').trim();
        if (text) {
          blocks.push(`<p>${text}</p>`);
        }
        currentParaLines = [];
      }
    };

    const flushList = () => {
      if (currentList && currentList.items.length > 0) {
        const listTag = currentList.type;
        const itemsHtml = currentList.items
          .map((item) => `<li>${item.trim()}</li>`)
          .join('');
        blocks.push(`<${listTag}>${itemsHtml}</${listTag}>`);
        currentList = null;
      }
    };

    for (const rawLine of rawLines) {
      const line = rawLine.trim();
      if (!line) continue;

      // Heading: e.g. ## Heading or ### Heading
      const headingMatch = line.match(/^#{1,6}\s+(.+)$/);
      if (headingMatch) {
        flushList();
        flushPara();
        blocks.push(`<h4>${headingMatch[1].trim()}</h4>`);
        continue;
      }

      // Bullet list item: e.g. - item or * item
      const bulletMatch = line.match(/^[-*]\s+(.+)$/);
      if (bulletMatch) {
        flushPara();
        if (!currentList || currentList.type !== 'ul') {
          flushList();
          currentList = { type: 'ul', items: [] };
        }
        currentList.items.push(bulletMatch[1]);
        continue;
      }

      // Numbered list item: e.g. 1. item
      const numMatch = line.match(/^\d+\.\s+(.+)$/);
      if (numMatch) {
        flushPara();
        if (!currentList || currentList.type !== 'ol') {
          flushList();
          currentList = { type: 'ol', items: [] };
        }
        currentList.items.push(numMatch[1]);
        continue;
      }

      // Regular line within a paragraph
      flushList();
      currentParaLines.push(line);
    }

    flushList();
    flushPara();

    return blocks.length > 0 ? blocks.join('') : match;
  });
}

/**
 * Safe HTML renderer for editorial descriptions and notes
 * Converts pre-sanitized HTML from the build importer into safe React elements
 */
export default function SafeHtml({ content, className = '' }) {
  const elements = useMemo(() => {
    if (!content || typeof content !== 'string') return null;

    const normalized = normalizeMarkdownInHtml(content);

    if (typeof window === 'undefined' || typeof DOMParser === 'undefined') {
      // Fallback for non-DOM environments: strip raw HTML tags
      return normalized.replace(/<[^>]*>/g, '');
    }

    try {
      const parser = new DOMParser();
      const doc = parser.parseFromString(normalized, 'text/html');
      return Array.from(doc.body.childNodes).map((node, index) =>
        domToReact(node, `node-${index}`),
      );
    } catch {
      return normalized.replace(/<[^>]*>/g, '');
    }
  }, [content]);

  if (!elements) return null;

  return <div className={`safe-html-root ${className}`}>{elements}</div>;
}
